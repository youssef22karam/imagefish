import type { Species } from '../engine/types';

/** recursive partial that also reaches into optional members (fins.pec, body.snout …) */
export type DP<T> = { [K in keyof T]?: NonNullable<T[K]> extends (infer U)[] ? U[] : NonNullable<T[K]> extends object ? DP<NonNullable<T[K]>> : T[K] };

/**
 * Measured lateral outlines.
 *   d = dorsal profile, v = ventral profile: flat [s, y, s, y, …] pairs,
 *   s = station from the snout tip (0) to the caudal base (1), y = distance from the snout axis (SL).
 * Each outline is normalised to the species' measured maximum body depth (or `D` when given), so the
 * numbers describe SHAPE: where the back peaks, how the forehead climbs, how the belly hangs, how the
 * trunk runs out into the peduncle.
 *   n   = snout exponent (0.45 bluff · 0.62 rounded · 0.85 wedge)
 *   fix = corrections of landmarks / fins that must move together with the new outline
 */
export interface OutlineEntry { d: number[]; v: number[]; n?: number; D?: number; fix?: DP<Species> }
export const O = (d: number[], v: number[], x: Omit<OutlineEntry, 'd' | 'v'> = {}): OutlineEntry => ({ d, v, ...x });

